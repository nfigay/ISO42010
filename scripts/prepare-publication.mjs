import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';

const ROOT = process.cwd();
const DIST = path.join(ROOT, 'dist');
const PUBLICATION = path.join(DIST, 'publication');
const MARKER = '.iso42010-generated-publication';
const publish = process.argv.includes('--publish');
if (process.argv.some(x => x.startsWith('--') && x !== '--publish')) throw new Error('Option inconnue');
const run = (cmd, args, opts={}) => {
  const result = spawnSync(cmd, args, {cwd: ROOT, encoding:'utf8', stdio:'pipe', ...opts});
  if (result.stdout) process.stdout.write(result.stdout);
  if (result.stderr) process.stderr.write(result.stderr);
  if (result.status !== 0) throw new Error(`${cmd} ${args.join(' ')} a échoué (${result.status ?? result.error?.message})`);
  return result.stdout.trim();
};
function git(...args) {
  const r = spawnSync('git', args, {cwd:ROOT, encoding:'utf8'});
  if(r.status !== 0) throw new Error(`git ${args.join(' ')}: ${r.stderr.trim()}`);
  return r.stdout.trim();
}
function filesUnder(dir) {
  return fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=> {
    const full=path.join(dir,e.name);
    if(e.isSymbolicLink()) throw new Error(`Lien symbolique interdit: ${full}`);
    return e.isDirectory() ? filesUnder(full) : e.isFile() ? [full] : [];
  });
}
function requireFile(f) { if(!fs.statSync(f,{throwIfNoEntry:false})?.isFile()) throw new Error(`Artefact manquant: ${f}`); }
if (!fs.existsSync(path.join(ROOT,'vite.config.js'))) throw new Error('Lancer depuis la racine ISO42010');
if (git('branch','--show-current') !== 'main') throw new Error('Branche main requise');
const sha=git('rev-parse','HEAD');
console.log(`SOURCE_COMMIT=${sha}`);
if (publish) {
  if (git('status','--porcelain')) throw new Error('Publication refusée : dépôt non propre');
  run('git',['fetch','origin','main']);
  if (git('rev-parse','origin/main') !== sha) throw new Error('origin/main différent de HEAD');
  console.log('SOURCE_REMOTE_ALIGNMENT=OK');
}
run('npm',['test']);
run('npm',['run','build']);
for(const rel of ['pages/index.html','pages/.nojekyll','standalone/index.html','server/workbench/index.html','modules/workbench/index.html']) requireFile(path.join(DIST,rel));
const sourceBase=path.join(DIST,'pages');
if (fs.existsSync(PUBLICATION)) {
  if(!fs.existsSync(path.join(PUBLICATION,MARKER))) throw new Error('Refus de remplacer dist/publication sans marqueur');
  fs.rmSync(PUBLICATION,{recursive:true,force:true});
}
fs.mkdirSync(PUBLICATION,{recursive:true});
fs.writeFileSync(path.join(PUBLICATION,MARKER),'generated by ISO42010 local publication script\n');
fs.cpSync(sourceBase,PUBLICATION,{recursive:true,force:true});
for(const rel of ['standalone','server','modules']) fs.cpSync(path.join(DIST,rel),path.join(PUBLICATION,rel),{recursive:true});
for(const rel of ['index.html','.nojekyll','standalone/index.html','server/workbench/index.html','modules/workbench/index.html']) requireFile(path.join(PUBLICATION,rel));
const provenance=`ISO42010 local Vite publication\nsource_commit=${sha}\nsource_branch=main\nbuild_targets=standalone,server,modules,pages\npublication_root=dist/publication\n`;
fs.writeFileSync(path.join(PUBLICATION,'ISO42010_PUBLICATION.txt'),provenance);
const paths=filesUnder(PUBLICATION).filter(f=>path.basename(f)!=='ISO42010_SHA256.txt').sort();
const manifest=paths.map(f=>`${crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex')}  ${path.relative(PUBLICATION,f).split(path.sep).join('/')}`).join('\n')+'\n';
fs.writeFileSync(path.join(PUBLICATION,'ISO42010_SHA256.txt'),manifest);
console.log(`PUBLICATION_FILES=${paths.length+1}`);
